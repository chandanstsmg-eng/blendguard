const dicts: Record<Lang, Partial<Record<TKey, string>>> = { en, hi, ml };

export const LANGS: { code: Lang; label: string; short: string }[] = [
  { code: 'en', label: 'English', short: 'EN' },
  { code: 'hi', label: 'हिन्दी', short: 'हिं' },
  { code: 'ml', label: 'മലയാളം', short: 'മ' },
];

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  let s = dicts[lang][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function hasKey(key: string): key is TKey {
  return key in en;
}

export function useT() {
  const lang = usePrefs((s) => s.lang);
  return Object.assign((key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars), { lang });
}

/** Translated message for an API error code, falling back to the server's English sentence. */
export function errorText(lang: Lang, code: string | undefined, fallback: string) {
  const key = `err.${code}`;
  return code && hasKey(key) ? translate(lang, key) : fallback || translate(lang, 'err.GENERIC');
}
